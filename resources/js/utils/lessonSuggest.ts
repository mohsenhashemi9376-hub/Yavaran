const pick = <T,>(list: T[], n: number): T => list[n % list.length];

/**
 * متن پیشنهادی برای یک گام. `variant` با هر کلیک افزایش می‌یابد تا پیشنهادها تکراری نشوند.
 * نتیجه null یعنی «درس» یا «روش» هنوز انتخاب نشده است.
 */
export const suggestForStep = (
  phase: SuggestPhase,
  ctx: { subject: string; methods: string[]; techniques: string[] },
  variant: number,
): Suggestion | null => {
  if (!ctx.subject.trim() || ctx.methods.length === 0) return null;
  const key = subjectKeyOf(ctx.subject);
  const bucket = key ?? 'generic';
  const method = pick(ctx.methods, variant);
  const technique = ctx.techniques.length ? pick(ctx.techniques, variant) : '';
  const techniqueNote = technique ? ` (با تکنیک «${technique}»)` : '';

  if (phase === 'motivation') {
    const base = pick(MOTIVATION[bucket], variant);
    return { teacher: `${base.teacher}${techniqueNote}`, student: base.student };
  }
  if (phase === 'wrapup') {
    const base = pick(WRAPUP[bucket], variant);
    return { teacher: `${base.teacher}${techniqueNote}`, student: base.student };
  }

  const guide = METHOD_GUIDE[method];
  const example = guide && key ? guide.examples[key] : '';
  const tech = TECHNIQUE_GUIDE[technique]?.examples[key ?? 'science'];
  const teacher = example
    ? `با روش «${method}»: ${example}${technique ? ` همچنین برای پویایی کلاس از تکنیک «${technique}» استفاده می‌کنم.` : ''}`
    : `با روش «${method}»${guide ? `: ${guide.summary}` : ' درس را اجرا می‌کنم.'}${tech && key ? ` نمونه با تکنیک «${technique}»: ${tech}` : ''}`;
  const student = METHOD_STUDENT[method] || 'در فعالیت‌های کلاسی مشارکت می‌کنند و یافته‌های خود را با کلاس به اشتراک می‌گذارند.';
  return { teacher, student };
};
