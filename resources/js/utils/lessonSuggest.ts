export const subjectKeyOf = (subject: string): GuideSubjectKey | null => {
  const s = (subject || '').replace(/ي/g, 'ی').replace(/ك/g, 'ک');
  if (/علوم|زیست|فیزیک|شیمی/.test(s)) return 'science';
  if (/فارسی|نگارش|ادبیات|املا/.test(s)) return 'persian';
  if (/ریاضی|هندسه|آمار/.test(s)) return 'math';
  if (/عرب/.test(s)) return 'arabic';
  if (/انگلیسی|زبان/.test(s)) return 'english';
  return null;
};

